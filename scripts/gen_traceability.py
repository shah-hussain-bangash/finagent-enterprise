"""Generate traceability and inventory docs from evidence (prompt §46, §62; ADR-0012).

Inputs : docs/requirements/requirements.json   (extracted from the source PDFs; 245 + MST IDs)
         docs/traceability/trace-map.yaml       (requirement -> implementation files)
         reports/junit.xml                      (latest pytest run; the ONLY source of pass/fail)
Outputs: docs/requirements/requirement-inventory.md
         docs/traceability/requirements-to-code.md
         docs/traceability/requirements-to-tests.md
         docs/traceability/coverage-summary.md

Status rules: APPROVED is never generated (no owner decisions exist). TEST PASSED requires >=1
linked test passed and none failed/errored in the run. Skipped tests count as TEST NOT RUN.
"""

from __future__ import annotations

import json
import sys
import xml.etree.ElementTree as ET
from collections import Counter, defaultdict
from datetime import UTC, datetime
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
REQS = ROOT / "docs/requirements/requirements.json"
TRACE = ROOT / "docs/traceability/trace-map.yaml"
JUNIT = ROOT / "reports/junit.xml"
BROWSER_JUNIT = ROOT / "reports/junit-browser.xml"  # `tasks.py test-browser` (real Chromium journey)
SOURCE = {
    "FAE-BRD-001": "BRD",
    "FAE-SRS-002": "SRS",
    "FAE-DIR-004": "DIR",
    "FAE-AER-005": "AER",
    "FAE-SPR-006": "SPR",
    "FAE-NFR-007": "NFR",
    "FAE-MASTER v1.0": "MST",
}


def esc(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def load_results() -> tuple[dict[str, list[tuple[str, str]]], dict[str, str]]:
    by_req: dict[str, list[tuple[str, str]]] = defaultdict(list)
    meta = {"run": "no junit file - tests NOT RUN", "counts": ""}
    if not JUNIT.exists():
        return by_req, meta
    for path in (JUNIT, BROWSER_JUNIT):
        if path.exists():
            _read_suite(path, by_req, meta, primary=path == JUNIT)
    return by_req, meta


def _read_suite(
    path: Path, by_req: dict[str, list[tuple[str, str]]], meta: dict[str, str], *, primary: bool
) -> None:
    root = ET.parse(path).getroot()  # noqa: S314 - trusted local file
    suite = root if root.tag == "testsuite" else root.find("testsuite")
    assert suite is not None
    run = f"{suite.get('timestamp', '?')} on {suite.get('hostname', '?')}"
    counts = (
        f"tests={suite.get('tests')} failures={suite.get('failures')} "
        f"errors={suite.get('errors')} skipped={suite.get('skipped')}"
    )
    if primary:
        meta["run"], meta["counts"] = run, counts
    else:  # the separate real-browser run is reported alongside, never merged silently
        meta["counts"] += f"; browser run {run}: {counts}"
    for case in suite.iter("testcase"):
        name = f"{case.get('classname')}::{case.get('name')}"
        if case.find("failure") is not None or case.find("error") is not None:
            outcome = "FAILED"
        elif case.find("skipped") is not None:
            outcome = "NOT RUN"
        else:
            outcome = "PASSED"
        for prop in case.iter("property"):
            if prop.get("name") == "requirements":
                for rid in (prop.get("value") or "").split(","):
                    by_req[rid].append((name, outcome))


def status(rid: str, trace: dict[str, dict[str, object]], results: dict[str, list[tuple[str, str]]]) -> str:
    outcomes = {o for _, o in results.get(rid, [])}
    if "FAILED" in outcomes:
        return "TEST FAILED"
    implemented = rid in trace
    if "PASSED" in outcomes:
        return "TEST PASSED (partial scope)" if trace.get(rid, {}).get("partial") else "TEST PASSED"
    if implemented:
        return "IMPLEMENTED - TEST NOT RUN"
    return "DRAFT REQUIREMENT"


def main() -> int:
    reqs = json.loads(REQS.read_text(encoding="utf-8"))
    trace: dict[str, dict[str, object]] = yaml.safe_load(TRACE.read_text(encoding="utf-8")) or {}
    known = {r["id"] for r in reqs}
    unknown = sorted(set(trace) - known)
    if unknown:
        print(f"trace-map references unknown IDs: {unknown}", file=sys.stderr)
        return 1
    results, meta = load_results()
    stamp = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    banner = (
        f"> Generated by `scripts/gen_traceability.py` at {stamp}. Test evidence: {meta['run']} "
        f"({meta['counts'] or 'none'}). All source requirements are DRAFT; none is APPROVED.\n"
    )

    inv = [
        "# Requirement Inventory\n",
        banner,
        "\nExtracted programmatically from the supplied PDFs. Formal series total: "
        f"{sum(1 for r in reqs if not r['id'].startswith('MST:'))} (matches RTM-008's 245). "
        "Master implementation IDs are namespaced `MST:` (ADR-0011).\n",
        "\n| ID | Source | Priority | Requirement (source wording, abridged by extraction) |"
        "\n|---|---|---|---|",
    ]
    inv += [
        f"| {r['id']} | {SOURCE.get(r['doc'], r['doc'])} | {r.get('kind', '')} | {esc(r['text'])} |"
        for r in reqs
    ]
    (ROOT / "docs/requirements/requirement-inventory.md").write_text(
        encoding="utf-8", newline="\n", data="\n".join(inv) + "\n"
    )

    code = [
        "# Requirements to Code\n",
        banner,
        "\n| ID | Status | Implementation | Note |\n|---|---|---|---|",
    ]
    tests = ["# Requirements to Tests\n", banner, "\n| ID | Status | Tests (outcome) |\n|---|---|---|"]
    counter: Counter[str] = Counter()
    for r in reqs:
        rid = r["id"]
        st = status(rid, trace, results)
        counter[st] += 1
        entry = trace.get(rid, {})
        files = "<br>".join(f"`{f}`" for f in entry.get("files", [])) or "-"  # type: ignore[union-attr]
        code.append(f"| {rid} | {st} | {files} | {esc(str(entry.get('note', '')))} |")
        linked = results.get(rid, [])
        cell = "<br>".join(f"`{n.split('.')[-1]}` {o}" for n, o in linked) or "-"
        tests.append(f"| {rid} | {st} | {cell} |")
    (ROOT / "docs/traceability/requirements-to-code.md").write_text(
        encoding="utf-8", newline="\n", data="\n".join(code) + "\n"
    )
    (ROOT / "docs/traceability/requirements-to-tests.md").write_text(
        encoding="utf-8", newline="\n", data="\n".join(tests) + "\n"
    )

    summary = ["# Coverage Summary\n", banner, "\n| Status | Requirements |\n|---|---|"]
    summary += [f"| {k} | {v} |" for k, v in sorted(counter.items())]
    summary.append(f"| **Total** | **{sum(counter.values())}** |")
    (ROOT / "docs/traceability/coverage-summary.md").write_text(
        encoding="utf-8", newline="\n", data="\n".join(summary) + "\n"
    )
    print("\n".join(summary))
    return 1 if counter["TEST FAILED"] else 0


if __name__ == "__main__":
    raise SystemExit(main())

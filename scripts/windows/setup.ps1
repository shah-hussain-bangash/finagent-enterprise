<#
.SYNOPSIS
  One-time local setup on Windows (PowerShell 5.1+). SYNTHETIC data only.
.DESCRIPTION
  Creates .venv, installs the Python package with dev extras, installs web dependencies, creates .env
  from .env.example with freshly generated LOCAL-ONLY secrets (never printed), starts PostgreSQL,
  Redis and the mock bank in Docker on configurable host ports, migrates, enables the restricted
  application role and seeds synthetic tenants. Safe to re-run: existing .env values are kept.
  Does not stop or change any other project's containers or ports.
.EXAMPLE
  powershell -ExecutionPolicy Bypass -File scripts\windows\setup.ps1 -PgPort 55432 -RedisPort 56379
#>
param(
    [int]$PgPort = 55432,
    [int]$RedisPort = 56379,
    [int]$ApiPort = 8001,
    [int]$WebPort = 3001
)
$ErrorActionPreference = "Stop"
$Root = Resolve-Path (Join-Path $PSScriptRoot "..\..")
Set-Location $Root

function Need($cmd, $hint) {
    if (-not (Get-Command $cmd -ErrorAction SilentlyContinue)) { throw "$cmd not found. $hint" }
}
Need python "Install Python 3.12 from python.org (tick 'Add to PATH')."
Need node "Install Node.js 22 LTS."
Need docker "Install Docker Desktop and start it."

function Secret([int]$bytes = 36) {
    $b = New-Object byte[] $bytes
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($b)
    return [Convert]::ToBase64String($b).Replace("+", "-").Replace("/", "_").TrimEnd("=")
}

if (-not (Test-Path ".venv")) {
    python -m venv .venv
    if ($LASTEXITCODE -ne 0) { throw "Could not create the project Python environment." }
}
& .venv\Scripts\python.exe -m pip install --upgrade pip | Out-Null
if ($LASTEXITCODE -ne 0) { throw "Could not update pip in the project Python environment." }
& .venv\Scripts\python.exe -m pip install -e ".[dev]"
if ($LASTEXITCODE -ne 0) { throw "Could not install the project Python dependencies." }
Push-Location apps\web
try {
    npm ci --no-audit --no-fund
    if ($LASTEXITCODE -ne 0) { throw "Could not install the portal dependencies." }
} finally {
    Pop-Location
}

if (-not (Test-Path ".env")) {
    $app = (Secret 24) -replace "[^A-Za-z0-9_-]", "x"
    $lines = @(
        "# LOCAL DEVELOPMENT ONLY (generated by scripts\windows\setup.ps1). Never commit.",
        "FINAGENT_ENVIRONMENT=local",
        "FINAGENT_AUTH_MODE=local",
        "FINAGENT_PG_HOST_PORT=$PgPort",
        "FINAGENT_REDIS_HOST_PORT=$RedisPort",
        "FINAGENT_API_HOST_PORT=$ApiPort",
        "FINAGENT_WEB_HOST_PORT=$WebPort",
        "FINAGENT_MIGRATION_DATABASE_URL=postgresql+psycopg://finagent:finagent@127.0.0.1:$PgPort/finagent",
        "FINAGENT_APP_DB_PASSWORD=$app",
        "FINAGENT_DATABASE_URL=postgresql+psycopg://finagent_app:$app@127.0.0.1:$PgPort/finagent",
        "FINAGENT_TEST_DATABASE_URL=postgresql+psycopg://finagent:finagent@127.0.0.1:$PgPort/finagent_test",
        "FINAGENT_TEST_REDIS_URL=redis://127.0.0.1:$RedisPort/0",
        "FINAGENT_REDIS_URL=redis://127.0.0.1:$RedisPort/0",
        "FINAGENT_WEB_AUTH_REDIS_URL=redis://127.0.0.1:$RedisPort/0",
        "FINAGENT_WEB_ORIGIN=http://127.0.0.1:$WebPort",
        "FINAGENT_DEV_JWT_SECRET=$(Secret 48)",
        "FINAGENT_WEB_SESSION_SECRET=$(Secret 48)",
        "FINAGENT_BANK_BASE_URL=http://127.0.0.1:8100"
    )
    [IO.File]::WriteAllLines((Join-Path $Root ".env"), $lines, (New-Object Text.UTF8Encoding $false))
    Write-Host ".env created with generated local-only secrets (not printed)."
} else {
    Write-Host ".env exists - kept unchanged."
}

docker compose up -d postgres redis mock-bank
if ($LASTEXITCODE -ne 0) { throw "Could not start the local dependencies. Check Docker and the Compose output above." }
Write-Host "Waiting for PostgreSQL..."
$databaseReady = $false
for ($i = 0; $i -lt 60; $i++) {
    docker compose exec -T postgres pg_isready -U finagent *> $null
    if ($LASTEXITCODE -eq 0) { $databaseReady = $true; break }
    Start-Sleep -Seconds 1
}
if (-not $databaseReady) { throw "PostgreSQL did not become ready. Migration and seeding were not started." }
& .venv\Scripts\python.exe scripts\tasks.py migrate db-app-role seed
if ($LASTEXITCODE -ne 0) { throw "Database setup failed. Review the output above before starting the portal." }
Write-Host "Setup complete. Start everything with: scripts\windows\start-dev.ps1"

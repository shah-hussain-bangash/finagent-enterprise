"""Object storage port for document bytes and exports (prompt §15 "object storage"; §18 object paths).

Keys are generated by the platform - `<tenant_id>/<namespace>/<uuid>` - and never contain user
input, so a filename cannot traverse paths or address another tenant's object. Every object is
encrypted with AES-256-GCM whose associated data is the full key, so bytes copied under another
key (another tenant, another document) fail authentication instead of decrypting.

* `LocalBlobStore`  - filesystem under a configured root (local/test).
* `AzureBlobStore`  - Azure Blob Storage via managed identity. LIVE NOT VERIFIED (no Azure
  account on this host); the client library is imported lazily (prompt §2).
"""

from __future__ import annotations

import os
import re
import uuid
from pathlib import Path
from typing import Any, Protocol

from finagent.core.crypto import Encryptor

_KEY = re.compile(r"^[0-9a-f-]{36}/[a-z][a-z0-9-]{1,31}/[0-9a-f-]{36}$")


class BlobNotFoundError(Exception):
    pass


def new_key(tenant_id: uuid.UUID, namespace: str) -> str:
    key = f"{tenant_id}/{namespace}/{uuid.uuid4()}"
    if not _KEY.fullmatch(key):
        raise ValueError("invalid storage namespace")
    return key


def key_tenant(key: str) -> uuid.UUID:
    if not _KEY.fullmatch(key):
        raise ValueError("invalid storage key")
    return uuid.UUID(key.split("/", 1)[0])


class BlobStore(Protocol):
    def put(self, key: str, data: bytes) -> None: ...

    def get(self, key: str) -> bytes: ...

    def delete(self, key: str) -> None: ...


class LocalBlobStore:
    def __init__(self, root: str | Path, encryptor: Encryptor) -> None:
        self._root, self._enc = Path(root).resolve(), encryptor

    def _path(self, key: str) -> Path:
        if not _KEY.fullmatch(key):
            raise ValueError("invalid storage key")
        path = (self._root / f"{key}.bin").resolve()
        if self._root not in path.parents:
            raise ValueError("storage key escapes the storage root")
        return path

    def put(self, key: str, data: bytes) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(".tmp")
        tmp.write_bytes(self._enc.encrypt(data, key.encode()))
        os.replace(tmp, path)  # atomic: a reader never sees a half-written object

    def get(self, key: str) -> bytes:
        path = self._path(key)
        if not path.exists():
            raise BlobNotFoundError(key)
        return self._enc.decrypt(path.read_bytes(), key.encode())

    def delete(self, key: str) -> None:
        path = self._path(key)
        if path.exists():
            path.unlink()


class AzureBlobStore:
    """Same encryption envelope as local; Azure adds service-side encryption at rest."""

    def __init__(self, account_url: str, container: str, encryptor: Encryptor) -> None:
        from azure.identity import DefaultAzureCredential
        from azure.storage.blob import BlobServiceClient

        service: Any = BlobServiceClient(account_url=account_url, credential=DefaultAzureCredential())
        self._container: Any = service.get_container_client(container)
        self._enc = encryptor

    def put(self, key: str, data: bytes) -> None:
        if not _KEY.fullmatch(key):
            raise ValueError("invalid storage key")
        self._container.upload_blob(name=key, data=self._enc.encrypt(data, key.encode()), overwrite=False)

    def get(self, key: str) -> bytes:
        from azure.core.exceptions import ResourceNotFoundError

        if not _KEY.fullmatch(key):
            raise ValueError("invalid storage key")
        try:
            raw: bytes = self._container.download_blob(key).readall()
        except ResourceNotFoundError as exc:
            raise BlobNotFoundError(key) from exc
        return self._enc.decrypt(raw, key.encode())

    def delete(self, key: str) -> None:
        from azure.core.exceptions import ResourceNotFoundError

        if not _KEY.fullmatch(key):
            raise ValueError("invalid storage key")
        try:
            self._container.delete_blob(key)
        except ResourceNotFoundError:
            return

"""Controlled report export (FR-030 Should; SPR-012; prompt §22 `POST /exports`).

An export is a Markdown document with case/report references, version, review status, evidence list
(ids + content hashes) and the claim-to-evidence links. Anything that is not the approved (or
finalized) version carries a DRAFT watermark on every section. Exports are stored encrypted, audited,
quota-charged by the API, and downloadable only by an authorized principal with CURRENT case access.
"""

from __future__ import annotations

import hashlib
import uuid
from typing import Any

from pydantic import BaseModel, ConfigDict, Field
from sqlalchemy import select
from sqlalchemy.orm import Session

from finagent.core.correlation import get_correlation_id
from finagent.core.errors import AppError, ErrorCode, not_found
from finagent.database.models import ApprovalRequest, OutboxEvent, Report, ReportExport, ReportVersion
from finagent.documents.storage import BlobStore, new_key
from finagent.security.authorization.policy import Permission, PrincipalContext, require
from finagent.services.audit_service import writer as audit
from finagent.services.case_service.queries import load_scoped_case
from finagent.services.evidence_service.snapshots import snapshot_items
from finagent.services.review_service.reports import version_view

WATERMARK = "DRAFT - NOT APPROVED - FOR INTERNAL REVIEW ONLY"


class ExportRequest(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)

    case_id: uuid.UUID
    version_no: int | None = Field(default=None, ge=1)


def _md_escape(text: str) -> str:
    return text.replace("\r", "").replace("<", "&lt;").replace(">", "&gt;")


def render(
    view: dict[str, Any], evidence: list[dict[str, Any]], kind: str, approval: ApprovalRequest | None
) -> str:
    lines = []
    if kind == "DRAFT":
        lines += [f"> **{WATERMARK}**", ""]
    lines += [
        "# AML investigation report",
        "",
        f"- Case: `{view['case_id']}`",
        f"- Report: `{view['report_id']}` version {view['version_no']} "
        f"({view['origin']}, author {view['author_label']})",
        f"- Review status: {'APPROVED' if kind == 'APPROVED' else 'NOT APPROVED'}"
        + (f" (approval request `{approval.id}`)" if approval else ""),
        f"- Evidence snapshot: `{view['snapshot_id']}`",
        "- Generated by FinAgent Enterprise (human-reviewed copilot). Not a regulatory filing.",
        "",
    ]
    for s in view["sections"]:
        lines += [f"## {_md_escape(s['title'])}", ""]
        if kind == "DRAFT":
            lines += [f"*{WATERMARK}*", ""]
        lines += [_md_escape(s["text"]), ""]
    lines += ["## Claims and evidence links", ""]
    for c in view["claims"]:
        refs = ", ".join(c["evidence_refs"] + c["citation_refs"]) or "none"
        lines.append(f"- [{c['claim_type']} / {c['support_status']}] {_md_escape(c['text'])} (refs: {refs})")
    lines += ["", "## Evidence list", ""]
    for e in evidence:
        lines.append(
            f"- `{e['id']}` {e['source_type']} {e['source_ref']} v{e['version_no']} "
            f"sha256:{e['content_hash']}"
        )
    return "\n".join(lines) + "\n"


def create_export(
    session: Session, ctx: PrincipalContext, body: ExportRequest, store: BlobStore
) -> dict[str, Any]:
    require(ctx, Permission.EXPORT_CREATE)  # MFA step-up (SPR-005)
    case = load_scoped_case(session, ctx, str(body.case_id))
    if case is None:
        raise not_found()
    report = session.scalar(
        select(Report).where(Report.tenant_id == ctx.tenant_id, Report.case_id == case.id)
    )
    if report is None:
        raise not_found()
    version_no = body.version_no or report.current_version_no
    version = session.scalar(
        select(ReportVersion).where(
            ReportVersion.tenant_id == ctx.tenant_id,
            ReportVersion.report_id == report.id,
            ReportVersion.version_no == version_no,
        )
    )
    if version is None:
        raise not_found()
    approval = session.scalar(
        select(ApprovalRequest).where(
            ApprovalRequest.tenant_id == ctx.tenant_id,
            ApprovalRequest.report_version_id == version.id,
            ApprovalRequest.status.in_(("APPROVED", "CONSUMED")),
        )
    )
    kind = "APPROVED" if approval is not None and version.version_no == report.current_version_no else "DRAFT"
    view = version_view(session, report, version, with_diff=False)
    evidence = [
        {
            "id": str(i.id),
            "source_type": i.source_type,
            "source_ref": i.source_ref,
            "version_no": i.version_no,
            "content_hash": i.content_hash,
        }
        for i in snapshot_items(session, ctx.tenant_id, version.snapshot_id)
    ]
    data = render(view, evidence, kind, approval).encode("utf-8")
    if len(data) > 5 * 1024 * 1024:
        raise AppError(ErrorCode.PAYLOAD_TOO_LARGE, "The export exceeds the bounded export size.")
    key = new_key(ctx.tenant_id, "exports")
    store.put(key, data)
    export = ReportExport(
        tenant_id=ctx.tenant_id,
        case_id=case.id,
        report_version_id=version.id,
        approval_request_id=approval.id if approval else None,
        kind=kind,
        media_type="text/markdown",
        storage_key=key,
        sha256=hashlib.sha256(data).hexdigest(),
        size_bytes=len(data),
        created_by=ctx.principal_id,
    )
    session.add(export)
    session.flush()
    audit.record(
        session,
        tenant_id=ctx.tenant_id,
        action="EXPORT_CREATED",
        object_type="report_export",
        object_id=str(export.id),
        outcome="SUCCESS",
        actor_principal_id=ctx.principal_id,
        actor_kind=ctx.kind.value,
        case_id=case.id,
        details={"kind": kind, "version_no": version.version_no, "sha256": export.sha256},
    )
    session.add(
        OutboxEvent(
            tenant_id=ctx.tenant_id,
            event_type="export.created.v1",
            schema_version="1",
            resource_id=str(export.id),
            correlation_id=get_correlation_id(),
            payload={"export_id": str(export.id), "case_id": str(case.id), "kind": kind},
        )
    )
    return {
        "export_id": str(export.id),
        "kind": kind,
        "version_no": version.version_no,
        "sha256": export.sha256,
        "size_bytes": export.size_bytes,
        "download_url": f"/api/v1/exports/{export.id}/content",
    }


def download(session: Session, ctx: PrincipalContext, raw_id: str, store: BlobStore) -> tuple[bytes, str]:
    require(ctx, Permission.EXPORT_CREATE)
    try:
        eid = uuid.UUID(raw_id)
    except ValueError as exc:
        raise not_found() from exc
    export = session.scalar(
        select(ReportExport).where(ReportExport.tenant_id == ctx.tenant_id, ReportExport.id == eid)
    )
    if export is None or load_scoped_case(session, ctx, str(export.case_id)) is None:
        raise not_found()  # current case scope re-checked at download time (SPR-011)
    data = store.get(export.storage_key)
    if hashlib.sha256(data).hexdigest() != export.sha256:
        raise AppError(ErrorCode.DEPENDENCY_UNAVAILABLE, "The export failed its integrity check.")
    audit.record(
        session,
        tenant_id=ctx.tenant_id,
        action="EXPORT_DOWNLOADED",
        object_type="report_export",
        object_id=str(export.id),
        outcome="SUCCESS",
        actor_principal_id=ctx.principal_id,
        actor_kind=ctx.kind.value,
        case_id=export.case_id,
        details={"sha256": export.sha256},
    )
    return data, export.media_type
